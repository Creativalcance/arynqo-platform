export type AcademyCopyKey = keyof typeof copy;
export function academyCopy(locale: Locale, key: AcademyCopyKey) {
  return copy[key][locales.indexOf(locale)];
}

export function academyRunMessage(locale: Locale, code: string) {
  const messages: Record<string, AcademyCopyKey> = {
    academy_delete_busy: "deleteBusy",
    academy_delete_failed: "deleteError",
    invalid_deletion: "deleteError",
    source_unavailable: "sourceUnavailable",
    source_empty: "sourceUnreadable",
    source_too_large: "sourceUnreadable",
    invalid_source: "invalidSource",
    invalid_length: "invalidLength",
    invalid_metadata: "metadataTooLong",
    monthly_limit: "monthlyLimit",
    already_running: "alreadyRunning",
    not_retryable: "notRetryable",
    not_regeneratable: "notRetryable",
    regeneration_exists: "regenerationExists",
    provider_or_generation_failed: "generationConnectionError",
    worker_timeout: "generationConnectionError",
  };
  if (messages[code]) return academyCopy(locale, messages[code]);
  const translationLength = /^invalid_translation_length_([a-z]{2})_(\d+)_(\d+)_\d+_\d+$/.exec(code);
  if (translationLength && isLocale(translationLength[1])) return academyCopy(locale, "translationLength")
    .replace("{language}", new Intl.DisplayNames([locale], { type: "language" }).of(translationLength[1]) || translationLength[1])
    .replace("{words}", translationLength[2]).replace("{characters}", translationLength[3]);
  if (/^missing_translation_structure_[a-z]{2}$/.test(code)) return academyCopy(locale, "translationStructure");
  const provider = /^provider_output_(incomplete|length|empty|invalid_json|refused|filtered)(?:_([a-z]{2}))?$/.exec(code);
  if (provider) {
    const message = academyCopy(locale, provider[1] === "empty" ? "providerEmpty"
      : ["refused", "filtered"].includes(provider[1]) ? "providerBlocked" : "providerIncomplete");
    return isLocale(provider[2]) ? academyCopy(locale, "providerLanguage")
      .replace("{language}", new Intl.DisplayNames([locale], { type: "language" }).of(provider[2]) || provider[2])
      .replace("{message}", message) : message;
  }
  const length = /^invalid_length_([a-z]{2})_(\d+)_(\d+)$/.exec(code);
  if (length && isLocale(length[1])) {
    const values: Record<string, string> = {
      language: new Intl.DisplayNames([locale], { type: "language" }).of(length[1]) || length[1],
      words: length[2],
      characters: length[3],
      minWords: String(ARTICLE_CONTENT_LIMITS.minWords),
      maxWords: String(ARTICLE_CONTENT_LIMITS.maxWords),
      maxCharacters: String(ARTICLE_CONTENT_LIMITS.maxCharacters),
    };
    return academyCopy(locale, "invalidLengthDetail").replace(/\{(\w+)\}/g, (_, key: string) => values[key]);
  }
  for (const [field, limit] of Object.entries(ARTICLE_METADATA_LIMITS)) {
    if (code === `invalid_metadata_${field}`) {
      const label = field === "title" ? "titleField" : field as AcademyCopyKey;
      return academyCopy(locale, "metadataFieldTooLong")
        .replace("{field}", academyCopy(locale, label))
        .replace("{limit}", String(limit));
    }
  }
  return code;
}
